#!/usr/bin/env node
// Regenerates packages/api/src/routes/ranking/data.ts from GitHub via the `gh` CLI.
// Usage: node scripts/ranking-data.mjs
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const REPO = "orowicki/gs-hackathon";
const LOGINS = ["orowicki", "mguszczin", "igorstec"];
const gh = (args) => JSON.parse(execFileSync("gh", [...args, "--repo", REPO], { encoding: "utf8", maxBuffer: 1 << 28 }));

const prs = gh(["pr", "list", "--state", "merged", "--limit", "500", "--json", "author,additions,deletions,mergedAt,number,title"]);
const issues = gh(["issue", "list", "--state", "closed", "--limit", "500", "--json", "assignees,number,title,closedAt"]);

for (const [name, list] of [["merged PRs", prs], ["closed issues", issues]])
  if (list.length >= 500) console.warn(`warning: ${name} list hit the --limit of 500; counts may be truncated`);

const entries = LOGINS.map((login) => {
  const mine = prs.filter((p) => p.author?.login === login);
  const dates = mine.map((p) => p.mergedAt).sort();
  const big = mine.reduce((b, p) => (p.additions + p.deletions > b.lines ? { number: p.number, title: p.title, lines: p.additions + p.deletions } : b), { number: 0, title: "", lines: 0 });
  return {
    login,
    mergedPrs: mine.length,
    linesAdded: mine.reduce((s, p) => s + p.additions, 0),
    linesRemoved: mine.reduce((s, p) => s + p.deletions, 0),
    issuesClosed: issues.filter((i) => i.assignees?.some((a) => a.login === login)).length,
    firstMerge: dates[0] ?? "",
    lastMerge: dates.at(-1) ?? "",
    biggestPr: big,
  };
});

const data = { generatedAt: new Date().toISOString(), repo: REPO, entries };
const out = `export interface RankingEntry {
  login: string;
  mergedPrs: number;
  linesAdded: number;
  linesRemoved: number;
  issuesClosed: number;
  firstMerge: string;
  lastMerge: string;
  biggestPr: { number: number; title: string; lines: number };
}
export interface RankingData {
  generatedAt: string;
  repo: string;
  entries: RankingEntry[];
}
// Generated by scripts/ranking-data.mjs; do not edit by hand.
export const rankingData: RankingData = ${JSON.stringify(data, null, 2)};
`;
writeFileSync(fileURLToPath(new URL("../packages/api/src/routes/ranking/data.ts", import.meta.url)), out);
console.log(JSON.stringify(data, null, 2));
